        "        prompt = f'''Extraia com rigor em LaTeX todas as questões de Matemática e Física da banca {banca.upper()} {ano}.\n",
        "Use delimitadores $...$ (inline) e $$...$$ (bloco). Se houver gráfico ou figura, devolva bounding box normalizada (0-1000).'''\n",
        "        \n",
        "        print('[*] Extraindo com gemini-flash-lite-latest...')\n",
        "        resp = client.models.generate_content(\n",
