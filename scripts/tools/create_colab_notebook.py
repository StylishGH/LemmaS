        "# 5. Processamento em Lote (Banca & Ano)\n",
        "def processar(banca='afa', ano='2024'):\n",
        "    raw_dir = ROOT_DIR / 'data' / 'sources' / banca / 'raw' / ano\n",
        "    proc_dir = ROOT_DIR / 'data' / 'sources' / banca / 'processed' / ano\n",
        "    img_dir = ROOT_DIR / 'data' / 'imagens' / banca / ano\n",
        "\n",
        "    provas, gabaritos = classificar_pdfs(raw_dir)\n",
        "    print(f'[{banca.upper()} {ano}] Provas:', [p.name for p in provas])\n",
