        "def recortar_figura(doc, bbox, out_dir, banca, ano, num_q, idx_fig):\n",
        "    out_dir.mkdir(parents=True, exist_ok=True)\n",
        "    pidx = bbox.pagina - 1\n",
        "    if pidx < 0 or pidx >= len(doc):\n",
        "        return ''\n",
        "    page = doc[pidx]\n",
        "    pix = page.get_pixmap(dpi=250)\n",
        "    img = Image.frombytes('RGB', [pix.width, pix.height], pix.samples)\n",
        "    w, h = img.size\n",
        "    l = max(0, int((bbox.xmin / 1000.0) * w) - 10)\n",
        "    t = max(0, int((bbox.ymin / 1000.0) * h) - 10)\n",
