        "def classificar_pdfs(raw_dir: Path) -> Tuple[List[Path], List[Path]]:\n",
        "    pdfs = sorted(list(raw_dir.rglob('*.pdf')))\n",
        "    provas, gabaritos = [], []\n",
        "    for pdf in pdfs:\n",
        "        nl = pdf.name.lower()\n",
        "        if any(g in nl for g in ['gabarito', 'gab', 'resposta']):\n",
        "            gabaritos.append(pdf)\n",
        "        else:\n",
        "            provas.append(pdf)\n",
        "    return provas, gabaritos\n",
