        "\n",
        "    client = genai.Client(api_key=os.environ['GEMINI_API_KEY'])\n",
        "    gabs_up = [client.files.upload(file=str(g)) for g in gabaritos]\n",
        "    questoes_finais = []\n",
        "\n",
        "    for p_pdf in provas:\n",
