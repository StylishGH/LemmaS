-- 1. FUNIL DE CONVERSÃO E ABANDONO (ANALYTICS)
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.analytics_funnel_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NOT NULL,
    stage TEXT NOT NULL CHECK (stage IN ('landing', 'questoes', 'resolver', 'tentativa')),
    aluno_id BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
    is_anonymous BOOLEAN NOT NULL DEFAULT true,
    referrer TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_analytics_funnel_stage_created 
    ON public.analytics_funnel_events (stage, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_analytics_funnel_session 
    ON public.analytics_funnel_events (session_id);

CREATE INDEX IF NOT EXISTS idx_analytics_funnel_created 
    ON public.analytics_funnel_events (created_at DESC);

ALTER TABLE public.analytics_funnel_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir insercao de eventos de funil" ON public.analytics_funnel_events;
CREATE POLICY "Permitir insercao de eventos de funil"
    ON public.analytics_funnel_events
    FOR INSERT
    TO anon, authenticated
    WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir leitura de funil para admins" ON public.analytics_funnel_events;
CREATE POLICY "Permitir leitura de funil para admins"
    ON public.analytics_funnel_events
    FOR SELECT
    TO authenticated
    USING (public.is_analytics_admin());

GRANT INSERT ON public.analytics_funnel_events TO anon, authenticated;
GRANT SELECT ON public.analytics_funnel_events TO authenticated;


