ALTER TABLE public.conceitos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tentativas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.revisao_espacada ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'usuarios' AND policyname = 'Acesso usuarios') THEN
        CREATE POLICY "Acesso usuarios" ON public.usuarios FOR ALL TO public USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'questoes' AND policyname = 'Leitura pública de questoes') THEN
        CREATE POLICY "Leitura pública de questoes" ON public.questoes FOR SELECT TO public USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'conceitos' AND policyname = 'Leitura pública de conceitos') THEN
        CREATE POLICY "Leitura pública de conceitos" ON public.conceitos FOR SELECT TO public USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'tentativas' AND policyname = 'Acesso tentativas') THEN
        CREATE POLICY "Acesso tentativas" ON public.tentativas FOR ALL TO public USING (true) WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'revisao_espacada' AND policyname = 'Acesso revisao_espacada') THEN
        CREATE POLICY "Acesso revisao_espacada" ON public.revisao_espacada FOR ALL TO public USING (true) WITH CHECK (true);
    END IF;
END $$;

