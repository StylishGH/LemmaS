-- 1. TABELA: socratic_hint_cache
-- Armazena dicas-base geradas por IA para amortizar latência e chamadas repetidas de API.
-- A chave lógica garante que uma questão idêntica com mesma solução, nível e modo
-- não gere custos repetidos nem duplicação de dados concorrentes.
CREATE TABLE IF NOT EXISTS public.socratic_hint_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key TEXT NOT NULL,
    questao_id BIGINT REFERENCES public.questoes(id) ON DELETE CASCADE,
    exercise_id TEXT NOT NULL,
    level INTEGER NOT NULL CHECK (level >= 1 AND level <= 5),
    pedagogical_preference TEXT NOT NULL DEFAULT 'conceitual',
    prompt_version TEXT NOT NULL DEFAULT 'v1.0-socratic',
    content_hash TEXT NOT NULL,
    hint_text TEXT NOT NULL,
    model_used TEXT NOT NULL,
    provider TEXT NOT NULL,
    latency_ms NUMERIC(10, 2) DEFAULT 0.0,
    hit_count INTEGER NOT NULL DEFAULT 1 CHECK (hit_count >= 1),
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    CONSTRAINT uq_socratic_hint_cache_key UNIQUE (cache_key)
);

-- 2. ÍNDICES OTIMIZADOS PARA BUSCA E AUDITORIA
CREATE INDEX IF NOT EXISTS idx_socratic_hint_cache_key ON public.socratic_hint_cache USING btree (cache_key);
CREATE INDEX IF NOT EXISTS idx_socratic_hint_cache_questao_id ON public.socratic_hint_cache USING btree (questao_id);
CREATE INDEX IF NOT EXISTS idx_socratic_hint_cache_lookup ON public.socratic_hint_cache USING btree (exercise_id, level, pedagogical_preference);
CREATE INDEX IF NOT EXISTS idx_socratic_hint_cache_created ON public.socratic_hint_cache USING btree (created_at DESC);

-- 3. SEGURANÇA E ROW LEVEL SECURITY (RLS)
ALTER TABLE public.socratic_hint_cache ENABLE ROW LEVEL SECURITY;

-- Leitura pública/compartilhada de dicas-base para todos os estudantes autenticados e visitantes
DROP POLICY IF EXISTS "Permitir leitura de dicas em cache" ON public.socratic_hint_cache;
CREATE POLICY "Permitir leitura de dicas em cache"
ON public.socratic_hint_cache FOR SELECT
TO public
USING (true);

-- Inserção permitida para serviços autenticados / backend
DROP POLICY IF EXISTS "Permitir insercao de dicas em cache por usuarios autenticados" ON public.socratic_hint_cache;
CREATE POLICY "Permitir insercao de dicas em cache por usuarios autenticados"
ON public.socratic_hint_cache FOR INSERT
TO public
WITH CHECK (true);

-- Atualização de hit_count e timestamps permitida para requisições de serviço
DROP POLICY IF EXISTS "Permitir atualizacao de hit_count em cache" ON public.socratic_hint_cache;
CREATE POLICY "Permitir atualizacao de hit_count em cache"
ON public.socratic_hint_cache FOR UPDATE
TO public
USING (true)
WITH CHECK (true);

-- Privilégios para roles padrão PostgREST
GRANT SELECT, INSERT, UPDATE ON public.socratic_hint_cache TO anon, authenticated, service_role;
