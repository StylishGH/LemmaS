-- 6. VIEW CANÔNICA DE EXPORTAÇÃO SFT (ChatML / Machine Learning)
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.vw_sft_dataset_export AS
SELECT 
    t.id AS tentativa_id,
    t.questao_id,
    q.materia,
    q.banca,
    q.ano,
    q.enunciado,
    q.gabarito AS gabarito_oficial,
    COALESCE(
        t.resposta_aluno, 
        substring(t.anotacoes from '\[RESPOSTA:([A-E])\]')
    ) AS resposta_aluno,
    COALESCE(
        t.texto_resolucao, 
        substring(t.anotacoes from '\[JUSTIFICATIVA_BRUTA:(.*?)\]')
    ) AS texto_resolucao,
    t.imagem_resolucao_path,
    t.acertou,
    t.tempo_segundos,
    ai.id AS avaliacao_id,
    ai.provedor_modelo,
    ai.nome_modelo,
    ai.versao_prompt,
    ai.output_raw,
    ai.output_estruturado,
    ai.confianca,
    ai.input_hash,
    t.data_hora AS data_tentativa
FROM public.tentativas t
JOIN public.questoes q ON q.id = t.questao_id
LEFT JOIN public.avaliacoes_ia ai ON ai.tentativa_id = t.id;

GRANT SELECT ON public.vw_sft_dataset_export TO anon, authenticated, service_role;
